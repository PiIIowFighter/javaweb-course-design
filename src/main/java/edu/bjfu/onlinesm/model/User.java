package edu.bjfu.onlinesm.model;

import java.io.Serializable;
import java.time.LocalDateTime;


public class User implements Serializable {

    private Integer userId;
    
    private String username;
    
    private String passwordHash;
    private String email;
    private String fullName;
    
    private String affiliation;
    
    private String researchArea;
    
    private String roleCode;
    
    private String status;
    
    private LocalDateTime registerTime;

    
    
    private Integer completedReviewCount;
    
    private Double avgReviewScore;

    public User() {
    }

    public User(Integer userId, String username, String passwordHash, String email,
                String fullName, String affiliation, String researchArea,
                String roleCode, String status, LocalDateTime registerTime) {
        this.userId = userId;
        this.username = username;
        this.passwordHash = passwordHash;
        this.email = email;
        this.fullName = fullName;
        this.affiliation = affiliation;
        this.researchArea = researchArea;
        this.roleCode = roleCode;
        this.status = status;
        this.registerTime = registerTime;
    }

    public Integer getUserId() {
        return userId;
    }

    public void setUserId(Integer userId) {
        this.userId = userId;
    }

    public String getUsername() {
        return username;
    }

    public void setUsername(String username) {
        this.username = username;
    }

    public String getPasswordHash() {
        return passwordHash;
    }

    public void setPasswordHash(String passwordHash) {
        this.passwordHash = passwordHash;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getFullName() {
        return fullName;
    }

    public void setFullName(String fullName) {
        this.fullName = fullName;
    }

    public String getAffiliation() {
        return affiliation;
    }

    public void setAffiliation(String affiliation) {
        this.affiliation = affiliation;
    }

    public String getResearchArea() {
        return researchArea;
    }

    public void setResearchArea(String researchArea) {
        this.researchArea = researchArea;
    }

    public String getRoleCode() {
        return roleCode;
    }

    public void setRoleCode(String roleCode) {
        this.roleCode = roleCode;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public LocalDateTime getRegisterTime() {
        return registerTime;
    }

    public void setRegisterTime(LocalDateTime registerTime) {
        this.registerTime = registerTime;
    }

    public Integer getCompletedReviewCount() {
        return completedReviewCount;
    }

    public void setCompletedReviewCount(Integer completedReviewCount) {
        this.completedReviewCount = completedReviewCount;
    }

    public Double getAvgReviewScore() {
        return avgReviewScore;
    }

    public void setAvgReviewScore(Double avgReviewScore) {
        this.avgReviewScore = avgReviewScore;
    }

    @Override
    public String toString() {
        return "User{" +
                "userId=" + userId +
                ", username='" + username + '\'' +
                ", email='" + email + '\'' +
                ", fullName='" + fullName + '\'' +
                ", roleCode='" + roleCode + '\'' +
                ", status='" + status + '\'' +
                '}';
    }
}

